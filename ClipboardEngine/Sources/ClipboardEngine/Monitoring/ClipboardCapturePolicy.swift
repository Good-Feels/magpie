import AppKit
import Foundation

/// Conservative filter, not authenticated source attribution. Pasteboard source
/// markers are untrusted hints and can only make the decision more restrictive.
public enum ClipboardCapturePolicy {
    public static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    public static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    public static func allows(
        types: Set<NSPasteboard.PasteboardType>,
        sourceBundleIDs: Set<String>,
        excludedBundleIDs: Set<String>
    ) -> Bool {
        types.isDisjoint(with: ignoredTypes)
            && sourceBundleIDs.isDisjoint(with: excludedBundleIDs)
    }
}

/// Retains every app observed during a polling interval, including the app active
/// at the interval's start. A rapid excluded-app -> editor switch rejects that
/// interval's clip. Background writers/unmarked origin cannot be identified reliably.
public struct ClipboardSourceInterval {
    private var observed: Set<String> = []

    public init(initialBundleID: String? = nil) { observe(initialBundleID) }

    public mutating func observe(_ bundleID: String?) {
        if let bundleID { observed.insert(bundleID) }
    }

    public mutating func finish(currentBundleID: String?) -> Set<String> {
        observe(currentBundleID)
        let result = observed
        observed = Set(currentBundleID.map { [$0] } ?? [])
        return result
    }
}
